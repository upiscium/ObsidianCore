/** Deterministic development-time CSS bundler. Never loads plugins or Vault data. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const LEGACY_SNIPPETS = Object.freeze([
  "callout-colors", "expense-dashboard-lite", "mobile-home-buttons", "monthly-expanse",
  "task-button", "task-controls", "task-status", "work-time"
]);
export const OUTPUT = ".obsidian/snippets/obsidian-core.css";
export const DISTRIBUTION_OUTPUT = "98-System/90-config/styles/obsidian-core.css";
export const OUTPUTS = Object.freeze([OUTPUT, DISTRIBUTION_OUTPUT]);
export const SOURCES = Object.freeze([
  ...LEGACY_SNIPPETS.map(name => `.obsidian/snippets/${name}.css`),
  ...["tokens", "components", "adapters"].map(name => `98-System/99-dev/styles/${name}.css`)
]);
const MAX_BYTES = 512 * 1024;
function regularPath(root, relative, mayBeMissing = false) {
  let current = path.resolve(root);
  const parts = relative.split("/");
  if (path.isAbsolute(relative) || parts.some(part => !part || part === "." || part === "..")) {
    throw new Error("unsafe build path");
  }
  parts.forEach((part, index) => {
    current = path.join(current, part);
    let stat;
    try { stat = fs.lstatSync(current); }
    catch (error) {
      if (mayBeMissing && index === parts.length - 1 && error.code === "ENOENT") return;
      throw error;
    }
    if (stat.isSymbolicLink() || (index < parts.length - 1 ? !stat.isDirectory() : !stat.isFile())) {
      throw new Error("build paths must be regular files/directories, not symlinks");
    }
    if (index === parts.length - 1 && stat.size > MAX_BYTES) throw new Error("build input exceeds limit");
  });
  return current;
}
export function readSource(root, relative) {
  const bytes = fs.readFileSync(regularPath(root, relative));
  if (bytes.length > MAX_BYTES) throw new Error("build input exceeds limit");
  const source = new TextDecoder("utf-8", { fatal: true }).decode(bytes).replace(/\r\n?/g, "\n");
  if (!source.trim() || /\u0000|@import\b|url\s*\(/i.test(source)) throw new Error("empty or remote-resource CSS is not allowed");
  return source.trimEnd() + "\n";
}
export function buildCss(root) {
  return "/* GENERATED by 98-System/99-dev/tools/build-styles.mjs. Do not edit this file. */\n"
    + SOURCES.map(relative => `\n/* SOURCE: ${relative} */\n${readSource(root, relative)}`).join("");
}
export function checkActivation(root) {
  const source = fs.readFileSync(regularPath(root, ".obsidian/appearance.json"), "utf8");
  const names = JSON.parse(source).enabledCssSnippets;
  if (!Array.isArray(names) || names.filter(name => name === "obsidian-core").length !== 1
      || names.some(name => LEGACY_SNIPPETS.includes(name))) {
    throw new Error("enable obsidian-core exactly once and disable its eight legacy inputs");
  }
}
export function checkBundle(root) {
  const css = buildCss(root);
  return OUTPUTS.every(relative => {
    const target = regularPath(root, relative, true);
    return fs.existsSync(target) && fs.readFileSync(target, "utf8") === css;
  });
}
function writeOutput(root, relative, css) {
  const target = regularPath(root, relative, true);
  const temp = `${target}.${process.pid}.tmp`;
  let created = false;
  try {
    const fd = fs.openSync(temp, "wx", 0o644); created = true;
    try { fs.writeFileSync(fd, css, "utf8"); fs.fsyncSync(fd); } finally { fs.closeSync(fd); }
    fs.renameSync(temp, target); created = false;
  } finally { if (created) fs.unlinkSync(temp); }
}
export function writeBundle(root) {
  const css = buildCss(root);
  for (const relative of OUTPUTS) writeOutput(root, relative, css);
}
