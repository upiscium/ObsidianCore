export function main(args = process.argv.slice(2), root = process.cwd()) {
  try {
    if (args.length === 0 || (args.length === 1 && args[0] === "--write")) {
      checkActivation(root); writeBundle(root); console.log("Core CSS bundle outputs written."); return 0;
    }
    if (args.length === 1 && args[0] === "--check") {
      checkActivation(root);
      if (!checkBundle(root)) throw new Error("generated CSS outputs are missing or stale; run build-styles.mjs --write");
      console.log("Core CSS bundle outputs / single activation: PASSED"); return 0;
    }
    if (args.length === 2 && args[0] === "--preview") {
      const css = buildCss(root); const directory = path.resolve(args[1]);
      // Caller chooses a NEW development output directory, never a Vault target.
      fs.mkdirSync(directory, { recursive: false });
      fs.writeFileSync(path.join(directory, "obsidian-core.css"), css, { flag: "wx" });
      for (const theme of ["dark", "light"]) fs.writeFileSync(path.join(directory, `${theme}.html`), renderPreview(css, theme), { flag: "wx" });
      console.log("Static style fixture written (no application actions)."); return 0;
    }
    throw new Error("usage: build-styles.mjs [--write|--check|--preview NEW_DIRECTORY]");
  } catch (error) { console.error(`Style build failed: ${error.message}`); return 1; }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
